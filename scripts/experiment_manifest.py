"""Generate docs/experiment_manifest.md from the artefacts themselves.

Several review rounds have turned up documentation numbers that no longer
matched the code -- a CP build size, a CP2 first-stage share, a tool count --
because each lived in prose that had to be updated by hand every time the
builder changed. Prose does not get re-derived; a generated file does.

Run this after any change to the graph, the builder or the config, and commit
the result. The protocol, the README and the paper can then all cite one file
that was read off the artefacts rather than remembered.
"""

from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from runner.config import load_experiment  # noqa: E402
from tcm_eval.scorers import CP_FAMILIES, is_primary_cp  # noqa: E402
from tcm_kg import load_kg  # noqa: E402
from tcm_tools.base import REGISTRY, ToolPhase  # noqa: E402
from tcm_kg.schema import Domain  # noqa: E402

CP_PATH = REPO_ROOT / "data" / "cp" / "TCM-CP.json"


def main() -> int:
    kg = load_kg()
    lines = [
        "# Experiment manifest (generated)",
        "",
        "Generated by `python scripts/experiment_manifest.py`. Every number is read",
        "from the artefacts, so the protocol, the README and the paper cannot drift",
        "apart from what the code produces. Do not edit by hand.",
        "",
        "## Knowledge graph",
        "",
        f"- content hash `{kg.content_hash()[:16]}`",
        f"- {len(kg.nodes)} nodes, {len(kg.edges)} edges",
        "",
        "## Tool surface",
        "",
        "| access domain | agent-phase | verification-phase |",
        "|---|---|---|",
    ]
    for domain in (Domain.CLINICAL, Domain.SAFETY, Domain.PATHWAY):
        agent = len(REGISTRY.specs_for(domain, phase=ToolPhase.AGENT))
        verify = len(REGISTRY.specs_for(domain, phase=ToolPhase.VERIFICATION))
        lines.append(f"| {domain.value} | {agent} | {verify} |")

    if CP_PATH.exists():
        items = json.loads(CP_PATH.read_text(encoding="utf-8"))
        counts = collections.Counter(i["subtask"] for i in items)
        ids = [i["id"] for i in items]
        lines += [
            "",
            "## TCM-CP",
            "",
            f"- **{len(items)} items**, {len(set(ids))} unique case ids "
            f"({len(ids) - len(set(ids))} duplicates)",
            f"- {len({i.get('disease') for i in items})} diseases",
            f"- primary endpoint: macro-average over "
            f"{len(CP_FAMILIES)} families ({', '.join(CP_FAMILIES)})",
            "",
            "| subtask | n | endpoint |",
            "|---|---|---|",
        ]
        for subtask, n in sorted(counts.items()):
            role = "primary" if is_primary_cp(subtask) else "**reported separately**"
            lines.append(f"| {subtask} | {n} | {role} |")

        provenance = collections.Counter(
            i["treatment_provenance"] for i in items if "treatment_provenance" in i
        )
        if provenance:
            lines += [
                "",
                "CP4 gold provenance: "
                + ", ".join(f"`{k}` {v}" for k, v in sorted(provenance.items())),
            ]

        report_path = Path(str(CP_PATH) + ".build_report.json")
        if report_path.exists():
            report = json.loads(report_path.read_text(encoding="utf-8"))
            lines += ["", "Dropped as unusable:", ""]
            lines += [f"- `{k}`: {v}" for k, v in sorted(report["dropped"].items())]
    else:
        lines += ["", "## TCM-CP", "", "_not built; run `scripts/build_tcm_cp.py`_"]

    lines += ["", "## Experiment configs", "", "| config | task | cases | conditions | samples |", "|---|---|---|---|---|"]
    for path in sorted((REPO_ROOT / "configs").glob("experiment.*.yaml")):
        try:
            config = load_experiment(path)
        except Exception:
            continue
        lines.append(
            f"| `{path.name}` | {config.task} | {config.dataset_limit or 'all'}"
            f"{' (stratified)' if config.dataset_stratify else ''} "
            f"| {len(config.conditions)} | {config.samples} |"
        )

    target = REPO_ROOT / "docs" / "experiment_manifest.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
