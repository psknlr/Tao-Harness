def load_pa(path: str | Path) -> Dataset:
    target = Path(path)
    if not target.exists():
        raise FileNotFoundError(f"dataset not found: {target}")
    if target.suffix.lower() in {".xlsx", ".xlsm"}:
        records: List[Mapping[str, Any]] = list(read_records(target))
    else:
        records = _load_json_records(target)
    mapping, sources = _bind(records, PA_ALIASES)
    items = _project(records, sources, "pa")
    for item in items:
        item["options"] = parse_options(item.get("options"))
        item["answer_letters"] = parse_letters(item.get("answer"))
        item["is_multi"] = len(item["answer_letters"]) > 1
        item["rule_id"] = str(item.get("rule_id") or "").strip().upper() or None
        item["_has_gold"] = bool(item["answer_letters"])
    n_multi = sum(1 for item in items if item["is_multi"])
    mapping.notes.append(f"{len(items) - n_multi} single-choice, {n_multi} multiple-choice")
    return Dataset("pa", items, mapping, target)


