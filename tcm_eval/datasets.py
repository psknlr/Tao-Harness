RESULT_FIELDS = ("clinical_information", "pathogenesis", "syndrome", "explanation")


def parse_result_file(path: str | Path) -> Dict[str, Dict[str, Any]]:
    """Read an official ``@``-separated answer file into gold records.

    Layout is ``case_id@task1@task2@task3@task4``. Only the first line for a
    given case counts, matching the official evaluator's de-duplication.
    """
    records: Dict[str, Dict[str, Any]] = {}
    text = Path(path).read_text(encoding="utf-8-sig")
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split("@")
        if len(parts) < 5:
            continue
        case_id = parts[0].strip().lstrip("﻿")
        if case_id in records:
            continue
        records[case_id] = {
            "clinical_information": parts[1].strip(),
            "pathogenesis_answer": parts[2].strip(),
            "syndrome_answer": parts[3].strip(),
            "explanation": "@".join(parts[4:]).strip(),
        }
    return records


def _default_result_path(dataset_path: Path) -> Optional[Path]:
    """Find the answer file that goes with a split, by the released layout."""
    stem = dataset_path.stem.lower()
    if "test" in stem:
        name = "Test_data_result.txt"
    elif "validation" in stem or "dev" in stem:
        name = "Validation_data_result.txt"
    else:
        return None
    for candidate in (
        dataset_path.parent / "Results" / name,
        dataset_path.parent / name,
        dataset_path.parent.parent / "Results" / name,
    ):
        if candidate.exists():
            return candidate
    return None


def load_sdt(path: str | Path, *, results_path: Optional[str | Path] = None) -> Dataset:
    target = Path(path)
    if not target.exists():
        raise FileNotFoundError(f"dataset not found: {target}")
    records = _load_json_records(target)
    mapping, sources = _bind(records, SDT_ALIASES)
    items = _project(records, sources, "sdt")

    gold_source = results_path or _default_result_path(target)
    gold: Dict[str, Dict[str, Any]] = {}
    if gold_source and Path(gold_source).exists():
        gold = parse_result_file(gold_source)
        mapping.notes.append(f"gold answers merged from {Path(gold_source).name}")

    for item in items:
        merged = gold.get(item["id"])
        if merged:
            # the held-out splits ship blank answer columns; the answer file is
            # the only place the labels exist
            for key in ("clinical_information", "pathogenesis_answer", "syndrome_answer"):
                if not str(item.get(key) or "").strip():
                    item[key] = merged[key]
            if not str(item.get("explanatory_summary") or "").strip():
                item["explanatory_summary"] = merged["explanation"]

        item["pathogenesis_options"] = parse_options(item.get("pathogenesis_options"))
        item["syndrome_options"] = parse_options(item.get("syndrome_options"))
        item["clinical_information_list"] = split_semicolon(item.get("clinical_information"))
        item["pathogenesis_letters"] = parse_letters(item.get("pathogenesis_answer"))
        item["syndrome_letters"] = parse_letters(item.get("syndrome_answer"))
        item["explanation_reference"] = _explanation_reference(item)
        item["_has_gold"] = bool(
            item["pathogenesis_letters"]
            or item["syndrome_letters"]
            or item["clinical_information_list"]
        )

    unlabelled = sum(1 for item in items if not item["_has_gold"])
    if unlabelled:
        mapping.notes.append(
            f"{unlabelled}/{len(items)} items have no gold answer; "
            f"they will be generated but not scored"
        )
    return Dataset("sdt", items, mapping, target)


def _explanatory_text(item: Mapping[str, Any]) -> str:
    return str(item.get("explanatory_summary") or "").strip()


def _explanation_reference(item: Mapping[str, Any]) -> str:
    """Task-4 reference: 临证体会 plus 辨证, as the answer files concatenate them."""
    summary = _explanatory_text(item)
    differentiation = str(item.get("syndrome_differentiation") or "").strip()
    if differentiation and differentiation not in summary:
        return f"{summary}{differentiation}" if summary else differentiation
    return summary


