def load_tcmsd(path: str | Path, *, vocab_path: Optional[str | Path] = None) -> Dataset:
    """TCM-SD: single-label syndrome classification over real EHR records."""
    target = Path(path)
    if not target.exists():
        raise FileNotFoundError(f"dataset not found: {target}")
    records = _load_json_records(target)
    mapping, sources = _bind(records, TCMSD_ALIASES)
    items = _project(records, sources, "tcmsd")

    vocab: List[str] = []
    candidate = Path(vocab_path) if vocab_path else target.parent / "syndrome_vocab.txt"
    if candidate.exists():
        vocab = [
            line.strip()
            for line in candidate.read_text(encoding="utf-8-sig").splitlines()
            if line.strip()
        ]
        mapping.notes.append(f"{len(vocab)} syndrome labels from {candidate.name}")

    for item in items:
        item["clinical_data"] = "\n".join(
            str(item.get(key) or "").strip()
            for key in ("chief_complaint", "description", "detection")
            if str(item.get(key) or "").strip()
        )
        item["label_space"] = vocab
        item["_has_gold"] = bool(str(item.get("syndrome") or "").strip())
    return Dataset("tcmsd", items, mapping, target)


def load_syndrome_knowledge(path: str | Path) -> Dict[str, Dict[str, Any]]:
    """TCM-SD's syndrome knowledge base, keyed by syndrome name.

    Not part of the graph and not used by the headline arms: it is an
    *external* resource, and folding it into a knowledge-graph condition would
    confound "what the graph adds" with "what a second corpus adds". It is
    loaded here so an explicit, separately-reported ablation can use it.
    """
    entries: Dict[str, Dict[str, Any]] = {}
    for record in _load_json_records(Path(path)):
        name = str(record.get("Name") or "").strip()
        if name:
            entries[name] = dict(record)
    return entries


