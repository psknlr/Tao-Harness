_OPTION_SPLIT_RE = re.compile(r"[;；]")
_OPTION_ENTRY_RE = re.compile(r"^\s*([A-Z])\s*[:：.、)）]\s*(.*)$", re.DOTALL)


def parse_options(raw: Any) -> Dict[str, str]:
    """Parse an option block into ``{letter: text}``.

    SDT writes ``"A:痰浊;B:耗损心气和心阴;..."`` on one line; PA writes
    ``"A. 中药名称\\nB. 中药数量"`` across lines. Both shapes appear in the
    released files, so both are accepted.
    """
    if isinstance(raw, Mapping):
        return {str(k).strip().upper()[:1]: str(v).strip() for k, v in raw.items()}
    text = str(raw or "").strip()
    if not text:
        return {}
    chunks: List[str] = []
    if "\n" in text:
        chunks = [line for line in text.splitlines() if line.strip()]
    else:
        chunks = [c for c in _OPTION_SPLIT_RE.split(text) if c.strip()]
    options: Dict[str, str] = {}
    for index, chunk in enumerate(chunks):
        match = _OPTION_ENTRY_RE.match(chunk.strip())
        if match:
            options[match.group(1).upper()] = match.group(2).strip()
        else:
            options[chr(ord("A") + index)] = chunk.strip()
    return options


def parse_letters(raw: Any) -> List[str]:
    """Parse a gold answer into sorted option letters.

    SDT writes ``"H;J"``; PA writes ``"ABCD"``. Both reduce to the same list.
    """
    text = str(raw or "")
    letters = [c.upper() for c in re.findall(r"[A-Za-z]", text)]
    seen: set = set()
    return sorted(l for l in letters if not (l in seen or seen.add(l)))


def split_semicolon(raw: Any) -> List[str]:
    """Split a ``;``-separated list, preserving the benchmark's own spelling."""
    text = str(raw or "").strip()
    if not text:
        return []
    return [part.strip() for part in _OPTION_SPLIT_RE.split(text) if part.strip()]


def _first_present(record: Mapping[str, Any], keys: Sequence[str]) -> Optional[str]:
    lowered = {str(k).lower(): k for k in record}
    for key in keys:
        if key in record:
            return key
        if key.lower() in lowered:
            return lowered[key.lower()]
    return None


def _bind(
    records: Sequence[Mapping[str, Any]], alias_map: Mapping[str, Sequence[str]]
) -> Tuple[FieldMapping, Dict[str, List[str]]]:
    """Bind logical fields over a sample of records, not just the first."""
    probe = records[: min(len(records), 25)]
    mapping = FieldMapping()
    sources: Dict[str, List[str]] = {}
    for logical, candidates in alias_map.items():
        counts: Dict[str, int] = {}
        for record in probe:
            key = _first_present(record, candidates)
            if key is not None and str(record.get(key) or "").strip():
                counts[key] = counts.get(key, 0) + 1
        if not counts:
            # a key that exists but is blank everywhere still binds: SDT's
            # held-out splits ship blank answer columns on purpose
            for record in probe:
                key = _first_present(record, candidates)
                if key is not None:
                    counts[key] = 0
                    break
        if not counts:
            mapping.missing.append(logical)
            continue
        ordered = sorted(
            counts,
            key=lambda k: (-counts[k], list(candidates).index(k) if k in candidates else 99),
        )
        mapping.bound[logical] = ordered[0]
        sources[logical] = ordered
    seen = {s for values in sources.values() for s in values}
    mapping.unmapped_keys = sorted({k for record in probe for k in record} - seen)
    return mapping, sources


def _project(
    records: Sequence[Mapping[str, Any]], sources: Mapping[str, Sequence[str]], prefix: str
) -> List[Dict[str, Any]]:
    items: List[Dict[str, Any]] = []
    for index, record in enumerate(records):
        item: Dict[str, Any] = {}
        for logical, keys in sources.items():
            value = None
            for key in keys:
                candidate = record.get(key)
                if candidate not in (None, ""):
                    value = candidate
                    break
            item[logical] = value
        if not str(item.get("id") or "").strip():
            item["id"] = f"{prefix}_{index:04d}"
        item["id"] = str(item["id"]).strip().lstrip("﻿")
        item["_raw"] = dict(record)
        items.append(item)
    return items


def _load_json_records(path: Path) -> List[Mapping[str, Any]]:
    text = path.read_text(encoding="utf-8-sig")
    stripped = text.lstrip()
    if path.suffix == ".jsonl" or (stripped and not stripped.startswith(("[", "{"))):
        return [json.loads(line) for line in text.splitlines() if line.strip()]
    try:
        payload = json.loads(text)
    except json.JSONDecodeError:
        # TCM-SD ships .json files that are actually JSON Lines
        return [json.loads(line) for line in text.splitlines() if line.strip()]
    if isinstance(payload, list):
        return payload
    if isinstance(payload, Mapping):
        for key in ("data", "items", "records", "questions", "cases"):
            value = payload.get(key)
            if isinstance(value, list):
                return value
        if all(isinstance(v, Mapping) for v in payload.values()):
            return [{"id": k, **v} for k, v in payload.items()]
    raise ValueError(f"unrecognised dataset structure in {path}")


