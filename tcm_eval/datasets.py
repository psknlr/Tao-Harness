"""Dataset loading for TCMEval-SDT, TCMEval-PA and TCM-SD.

Written against the released files, not against a guess at their schema.

**TCMEval-SDT** ships three JSON arrays (200 train / 50 validation / 50 test)
with Title-Case keys, and is a *four-task* benchmark rather than a single
syndrome-naming task:

===== ======================================= ================== ======
task  field                                   form               weight
===== ======================================= ================== ======
1     ``Clinical Information``                ``;``-separated    0.2
2     ``Answers of TCM Pathogenesis``         option letters     0.3
3     ``Answers of TCM Syndrome``             option letters     0.4
4     ``Explanatory Summary`` + ``Syndrome Differentiation``  free text  0.1
===== ======================================= ================== ======

Tasks 2 and 3 present ten options each (A-J), generated by the benchmark's own
``generate_multiple_choice_options.py``, and may have more than one correct
answer.

The validation and test JSONs carry **blank** answer fields -- the gold labels
live in ``Results/*.txt`` in the same ``@``-separated format the official
evaluator consumes. The loader merges them by medical-record ID, so pointing
at the test split gives a scorable dataset instead of silently scoring
everything against empty strings.

**TCMEval-PA** ships as a workbook (328 items: 297 single-, 31
multiple-choice) with ``Rule_ID`` values in the A-001..N-009/C-001 scheme that
the per-rule analysis depends on.

**TCM-SD** is a third, larger corpus (JSON Lines, 43k train / 5.5k dev, 148
normalised syndrome labels) shipped with a 1,027-entry syndrome knowledge base.
"""

